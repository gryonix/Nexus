    val allCodes: List<String> = regionByCode.keys.sorted()

    fun codesIn(region: CountryRegion): List<String> =
        regionByCode.filterValues { it == region }.keys.sorted()

    fun codesIn(continent: Continent): List<String> =
        regionByCode.filterValues { it.continent == continent }.keys.sorted()

    fun name(code: String, locale: java.util.Locale = java.util.Locale.getDefault()): String =
        java.util.Locale("", code).getDisplayCountry(locale).ifEmpty { code }

    /** Two-letter code → the flag emoji, matching `SecurityCard`'s own `flag()`. */
    fun flag(code: String): String {
        val upper = code.uppercase()
        if (upper.length != 2 || !upper.all { it.isLetter() && it.code < 128 }) return ""
        return upper.map { Character.toChars(127_397 + it.code).concatToString() }.joinToString("")
    }
